% =============================================================================

function bus = build_bus_from_fields_(description, fields)
% Generic Simulink.Bus constructor used by every bus above.
% fields cell: each entry {name, dims, units, datatype, description}.
    elems(numel(fields), 1) = Simulink.BusElement();
    for k = 1:numel(fields)
        e = Simulink.BusElement();
        e.Name           = fields{k}{1};
        e.Dimensions     = fields{k}{2};
        e.DataType       = fields{k}{4};
        e.SampleTime     = -1;
        e.Complexity     = 'real';
        e.DimensionsMode = 'Fixed';
        e.Description    = fields{k}{5};
        e.DocUnits       = fields{k}{3};
        elems(k) = e;
    end
    bus = Simulink.Bus();
    bus.Description = description;
    bus.Elements    = elems;
end
