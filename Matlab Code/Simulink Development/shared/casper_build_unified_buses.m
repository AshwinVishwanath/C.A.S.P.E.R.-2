function bus = build_sensor_input_bus()
% Identical to TruthBus by design — renamed for visual-model clarity.
    fields = { ...
        {'pos_NED',          3, 'm',      'double', 'world-frame NED position'}, ...
        {'vel_NED',          3, 'm/s',    'double', 'world-frame NED velocity'}, ...
        {'accel_NED',        3, 'm/s^2',  'double', 'world-frame NED net accel (gravity-free)'}, ...
        {'quat_std',         4, '',       'double', 'body-to-NED quat scalar-first [w x y z]'}, ...
        {'omega_body_std',   3, 'rad/s',  'double', 'body-frame angular rate'}, ...
        {'time_s',           1, 's',      'double', 'simulation time'}, ...
        {'mach',             1, '',       'double', 'Mach number'}, ...
        {'air_density_kgm3', 1, 'kg/m^3', 'double', 'air density'}, ...
        {'air_temp_K',       1, 'K',      'double', 'air temperature'}, ...
        {'air_pressure_pa',  1, 'Pa',     'double', 'air pressure'} ...
    };
    bus = build_bus_from_fields_('SensorInputBus (unified truth→sensors)', fields);
end

