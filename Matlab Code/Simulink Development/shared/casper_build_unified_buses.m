function buses = casper_build_unified_buses()
%CASPER_BUILD_UNIFIED_BUSES Construct the unified bus dialect for Phase 0 visual model.
%
% Synopsis:
%   buses = casper_build_unified_buses()
%
% Returns a struct of six Simulink.Bus objects. Caller is responsible for
% placing them in the base workspace under matching names:
%
%   buses = casper_build_unified_buses();
%   for f = fieldnames(buses)', assignin('base', f{1}, buses.(f{1})); end
%
% Buses:
%   SensorInputBus  — unified sensor-input dialect (identical to TruthBus;
%                     renamed for the visual-model wiring so consumers don't
%                     need to know about the truth/sensor separation).
%   IMUOutputBus    — IMU subsystem output (LSM6DSO32 + ADXL372 sharing one
%                     bus; ADXL fields populated only post-launch).
%   BaroOutputBus   — MS5611 subsystem output.
%   MagOutputBus    — MMC5983MA + radio interference subsystem output.
%   GPSOutputBus    — MAX-M10M subsystem output.
%   EstimateBus     — combined attitude + ESKF estimator state.
%
% Used by:
%   T11 visual top-level model casper_sim_phase0.slx
%   T03 imu_block_visual.slx
%   T04/T05/T06 bus-adapter subsystems
%   T10 validation_block (interface unified from 14 inports → 3 bus inports)
%
% See plan: lets-first-get-started-gentle-newt.md "Bus design (foundation)".

    buses = struct();
    buses.SensorInputBus = build_sensor_input_bus();
    buses.IMUOutputBus   = build_imu_output_bus();
    buses.BaroOutputBus  = build_baro_output_bus();
    buses.MagOutputBus   = build_mag_output_bus();
    buses.GPSOutputBus   = build_gps_output_bus();
    buses.EstimateBus    = build_estimate_bus();
end

