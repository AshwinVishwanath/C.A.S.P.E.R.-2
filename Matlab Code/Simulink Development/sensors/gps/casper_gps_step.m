function [lat_deg7, lon_deg7, alt_msl_mm, ...
          vel_n_mm_s, vel_e_mm_s, vel_d_mm_s, ...
          fix_type, num_sv, data_ready] = casper_gps_step( ...
            pos_NED, vel_NED, time_s, ...
            lat0_deg, lon0_deg, alt0_m, earth_radius_m, ...
            sigma_h_m, sigma_v_m, sigma_vel_mps, ...
            vel_thresh_mps, alt_thresh_m, reacquire_s, seed)
%CASPER_GPS_STEP Aggregate GPS-sensor model: position+noise -> COCOM -> hold -> latency.
%
% Synopsis:
%   [lat_deg7, lon_deg7, alt_msl_mm, vel_n_mm_s, vel_e_mm_s, vel_d_mm_s, ...
%    fix_type, num_sv, data_ready] = casper_gps_step( ...
%       pos_NED, vel_NED, time_s, lat0_deg, lon0_deg, alt0_m, ...
%       earth_radius_m, sigma_h_m, sigma_v_m, sigma_vel_mps, ...
%       vel_thresh_mps, alt_thresh_m, reacquire_s, seed)
%
% Calls (in order, matching the T06 §4 signal-flow diagram):
%   1. casper_gps_cocom_check    - cocom gate, fix_type, num_sv schedule
%   2. casper_gps_position_model - truth -> lat/lon/alt/vel + white noise
%   3. casper_gps_hold_lastvalid - hold position/velocity during COCOM
%   4. casper_gps_latency        - one-sample (100 ms @ 10 Hz) FIFO delay
%
% All persistent state lives inside the four helpers; this wrapper is
% itself stateless.
%
% Source firmware reference:
%   Software/App/drivers/max_m10m.c (NAV-PVT producer).

%#codegen

    % 1. COCOM gate + fix-type / num_sv schedule (uses truth, not noisy).
    [cocom_active, fix_now, sv_now] = casper_gps_cocom_check( ...
        vel_NED, pos_NED, time_s, vel_thresh_mps, alt_thresh_m, reacquire_s);

    % 2. Position / velocity from truth + noise.
    [lat_raw, lon_raw, alt_raw, vn_raw, ve_raw, vd_raw] = ...
        casper_gps_position_model(pos_NED, vel_NED, ...
            lat0_deg, lon0_deg, alt0_m, earth_radius_m, ...
            sigma_h_m, sigma_v_m, sigma_vel_mps, seed);

    % 3. Hold last-valid during COCOM dropout (per §5.3 step 3).
    [lat_h, lon_h, alt_h, vn_h, ve_h, vd_h] = ...
        casper_gps_hold_lastvalid(cocom_active, ...
            lat_raw, lon_raw, alt_raw, vn_raw, ve_raw, vd_raw);

    % 4. 100 ms latency FIFO.
    [lat_deg7, lon_deg7, alt_msl_mm, vel_n_mm_s, vel_e_mm_s, vel_d_mm_s, ...
     fix_type, num_sv, data_ready] = casper_gps_latency( ...
        lat_h, lon_h, alt_h, vn_h, ve_h, vd_h, fix_now, sv_now);
end
